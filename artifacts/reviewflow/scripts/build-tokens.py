#!/usr/bin/env python3
"""design/tokens.json -> src/styles/tokens.css (+ design/tokens-contrast.md).
Exits 1 if any contrast floor fails.
Colour model: every role = mix(ink, paper, pct) in sRGB, or paper / alpha of paper /
alpha of the darker of the two ("shade"), or the semantic exception (danger/warn)
and its 6% wash over paper.

Run from artifacts/reviewflow/:  python3 scripts/build-tokens.py
"""
import json, re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
T = json.loads((ROOT / "design" / "tokens.json").read_text())


def rgb(h):
    h = h.lstrip("#")
    return [int(h[i : i + 2], 16) for i in (0, 2, 4)]


def hexs(c):
    return "#" + "".join(f"{round(v):02X}" for v in c)


def mix(a, b, t):
    return hexs([x * t + y * (1 - t) for x, y in zip(rgb(a), rgb(b))])


def lum(h):
    c = [v / 255 for v in rgb(h)]
    c = [v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4 for v in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]


def cr(a, b):
    la, lb = sorted([lum(a), lum(b)], reverse=True)
    return (la + 0.05) / (lb + 0.05)


def rgba(h, a):
    r, g, b = rgb(h)
    return f"rgb({r} {g} {b} / {a})"


def resolve(theme, spec):
    th = T["themes"][theme]
    paper, ink = th["paper"], th["ink"]
    shade = paper if lum(paper) < lum(ink) else ink
    if spec == "paper":
        return paper, paper
    if spec.startswith("paper@"):
        return rgba(paper, spec[6:]), paper
    if spec.startswith("shade@"):
        return rgba(shade, spec[6:]), None
    if spec.startswith("ink."):
        k = spec[4:]
        pct = th["muted"] if k == "muted" else int(k)
        c = mix(ink, paper, pct / 100)
        return c, c
    if spec.startswith("exception."):
        name, _, wash = spec[10:].partition("~")
        c = th["exception"][name]
        if wash:
            c = mix(c, paper, int(wash) / 100)
        return c, c
    raise ValueError(spec)


def track_value(s):
    """Resolve a type role track: number → Nem, or 'label' → var(--label-track)."""
    t = s["track"]
    if t == "label":
        return "var(--label-track)"
    return f"{t}em"


out, report, fails = [], [], []
out.append("/* GENERATED by build-tokens.py from design/tokens.json. Do not edit by hand. */")
# ---- non-colour tokens
r = [":root{"]
for k, v in T["type"]["families"].items():
    r.append(f"  --font-{k}:{v};")
label_track = T["type"].get("labelTrack", 0.1)
r.append(f"  --label-track:{label_track}em;")
for name, s in T["type"]["roles"].items():
    r += [
        f"  --{name}-family:var(--font-{s['family']});",
        f"  --{name}-size:{s['size']}px;",
        f"  --{name}-line:{s['line']};",
        f"  --{name}-weight:{s['weight']};",
        f"  --{name}-track:{track_value(s)};",
    ]
for k, v in T["space"].items():
    r.append(f"  --space-{k}:{v}px;")
r.append(f"  --touch:{T['touch']}px;  --border:{T['border']};")
for k, v in T["radius"].items():
    r.append(f"  --radius-{k}:{v};")
for k, v in T["motion"].items():
    if k.startswith(("ease", "stagger")):
        r.append(f"  --{k}:{v};")
    elif k == "rise":
        r.append(f"  --rise:{v};")
    else:
        r.append(f"  --dur-{k}:{v};")
for k, v in T["layers"].items():
    r.append(f"  --layer-{k}:{v};")
for k, v in T["layout"].items():
    r.append(f"  --{k}:{v}px;" if str(v).isdigit() else f"  --{k}:{v};")
r.append("}")
out += r
# ---- colour themes
for i, (theme, th) in enumerate(T["themes"].items()):
    sel = f':root,[data-theme="{theme}"]' if i == 0 else f'[data-theme="{theme}"]'
    lines = [
        f"{sel}{{",
        f"  color-scheme:{'dark' if lum(th['paper']) < .2 else 'light'};",
        f"  --paper:{th['paper']}; --ink:{th['ink']};",
    ]
    for p in T["ramp"]:
        lines.append(f"  --ink-{p}:{mix(th['ink'], th['paper'], p / 100)};")
    solid = {}
    for role, spec in T["roles"].items():
        val, s = resolve(theme, spec)
        solid[role] = s
        lines.append(f"  --{role}:{val};")
    paper, ink = th["paper"], th["ink"]
    shade = paper if lum(paper) < lum(ink) else ink
    sh = T["shadow"]
    if sh == "none":
        lines.append("  --shadow:none;")
    else:
        sh = re.sub(
            r"shade@([0-9.]+)",
            lambda m: rgba(shade, float(m.group(1)) * (2.2 if shade == paper else 1)),
            sh,
        )
        lines.append(f"  --shadow:{sh};")
    lines.append("}")
    out += lines
    # contrast
    report.append(f"\n### {th['label']} (paper {th['paper']}, ink {th['ink']}, muted = ink {th['muted']}%)\n")
    report.append("| Role | On | FG | BG | Ratio | Floor | Pass |\n|---|---|---|---|---|---|---|")
    for kind, floor in (("checks", T["contrast"]["text"]), ("nonTextChecks", T["contrast"]["nonText"])):
        for fg, bgs in T["contrast"][kind]:
            for bg in bgs:
                ratio = cr(solid[fg], solid[bg])
                ok = ratio >= floor
                if not ok:
                    fails.append(f"{theme}: {fg} on {bg} = {ratio:.2f} < {floor}")
                report.append(
                    f"| {fg}{' (non-text)' if kind == 'nonTextChecks' else ''} | {bg} | {solid[fg]} | {solid[bg]} | {ratio:.2f}:1 | {floor} | {'✅' if ok else '❌'} |"
                )
# ---- type role classes + reduced motion
for name, s in T["type"]["roles"].items():
    extra = (" text-transform:uppercase;" if s.get("case") == "uppercase" else "") + (
        " font-variant-numeric:tabular-nums;" if s.get("numeric") else ""
    )
    out.append(
        f".t-{name}{{font-family:var(--{name}-family);font-size:var(--{name}-size);line-height:var(--{name}-line);"
        f"font-weight:var(--{name}-weight);letter-spacing:var(--{name}-track);{extra}}}"
    )
nar = T["type"]["narrow"]
out.append("@media (max-width:860px){:root{" + "".join(f"--{k}-size:{v}px;" for k, v in nar.items()) + "}}")
out.append(
    "@media (prefers-reduced-motion:reduce){:root{--dur-fast:0s;--dur-base:0s;--dur-slow:0s;--dur-theme:0s;--stagger:0ms}}"
)

css_path = ROOT / "src" / "styles" / "tokens.css"
contrast_path = ROOT / "design" / "tokens-contrast.md"
css_path.parent.mkdir(parents=True, exist_ok=True)
css_path.write_text("\n".join(out) + "\n")
contrast_path.write_text(
    "## Contrast per theme and role (generated by build-tokens.py)\n" + "\n".join(report) + "\n"
)
print(f"{css_path.relative_to(ROOT)} written ({len(out)} lines); {len(fails)} contrast failures")
for f in fails:
    print("  FAIL", f)
sys.exit(1 if fails else 0)
